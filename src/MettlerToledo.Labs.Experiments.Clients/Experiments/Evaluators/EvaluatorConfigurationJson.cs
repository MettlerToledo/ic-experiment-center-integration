using System.Collections.Generic;
using System.Text.Json.Serialization;

namespace MettlerToledo.Labs.Experiments.Clients.Experiments.Evaluators;

/// <summary>
/// Defines an evaluators that is used to analyze data form an instruement.
/// </summary>
[JsonObjectCreationHandling(JsonObjectCreationHandling.Populate)]
public class EvaluatorConfigurationJson
{
    /// <summary>
    /// The name of the evaluator.
    /// </summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// The parameters of the evaluator.
    /// </summary>
    public IList<EvaluatorParameterJson> Parameters { get; set; } = new List<EvaluatorParameterJson>();

    /// <summary>
    /// The trends that are generated by the evaluator.
    /// </summary>
    public IList<TrendDefinitionJson> Trends { get; set; } = new List<TrendDefinitionJson>();
}
